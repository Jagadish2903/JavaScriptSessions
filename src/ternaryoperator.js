//Ternary Operator =>  ? :

let amount =50;
let flag=amount>=10 ? true:false;
console.log(flag);//true


let element='link';
let action=element==='link'?'click':'dontClick'
console.log(action);//click


//Console.log we can write multiple values as well 
let name ="Jaga";
let age=30;
let salary=22.33;
let isActive=true;
console.log(name,age,salary,isActive);//Jaga 30 22.33 true



//Multiple conditions operator 
let m=10;
